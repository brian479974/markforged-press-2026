"""媒體中心首頁新聞卡片：依分類分區、同一類依新聞日期新到舊（2026-10-28 建立）

為什麼有這支：Brian 10-28 問「報導的順序為什麼老是變來變去」。查下來，首頁從來沒有排序規則，
卡片位置是每次上稿時由上稿的人手動插進 index.html，插在哪就排在哪（9 月有一段 3 月的舊卡排第一；
兩次推檔事故把卡片蓋掉又補回）。他定的規則：依分類分區，同一類依日期新到舊（日期的定義見下方規則）。

規則：
- 分類與每篇文章屬於哪一類 → news_categories.json（唯一來源）。新文章沒登記 → exit 1，不准猜。
- 同一類裡依「新聞本身的日期」新到舊；同一天的維持原本先後。日期登記在 news_categories.json 的 dates，
  本程式會把它寫進卡片上的 <span class="press-date">YYYY.MM.DD</span>，卡片不手改日期。
  （2026-10-28 Brian 定案：用新聞發生或原始公開那天，不用我們放上網站那天 —— 起因是 Alstom 2021 年的
  webinar 10/27 上站後印成 2026.10.27、排在客戶案例第一張，看起來像最新消息。主要素材有好幾份的取最新那份。）
- 一類的卡片數是奇數 → 最新那張用整列寬卡（.press-card.wide），兩欄才不會在最後落單一張。
- 已裁示不上首頁的文章（off_homepage）出現在首頁 → exit 1；要拿掉一張卡必須用 --drop 明講。
- 只改 NEWS:START～NEWS:END 這一段；寫檔前保證卡片一張都沒少（--drop 指定的除外）。

用法：
  python3 _build/news_order.py                 # 重排 index.html 與 index-en.html
  python3 _build/news_order.py --check         # 只檢查不寫檔；順序不對 exit 1（site_push.py 推檔前會跑）
  python3 _build/news_order.py --drop soulforge   # 拿掉一張卡（只限 off_homepage 登記過的）
上新文章的流程：先把 slug 登記進 news_categories.json → 卡片插在新聞區任何位置 → 跑本程式。
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CFG = json.loads(Path(__file__).with_name('news_categories.json').read_text(encoding='utf-8'))
PAGES = {'index.html': 'zh', 'index-en.html': 'en'}

START = '<!-- NEWS:START'
END = '<!-- NEWS:END -->'
CARD = re.compile(r'<a href="([^"]+)" class="press-card(?: wide)?">.*?</a>', re.S)
OPEN = re.compile(r'^<a href="([^"]+)" class="press-card(?: wide)?">')
DATE = re.compile(r'<span class="press-date">\s*(\d{4})\.(\d{2})\.(\d{2})\s*</span>')
STYLE = '''      <style>
        #news .news-cat{display:flex;align-items:baseline;flex-wrap:wrap;gap:4px 16px;margin:72px 0 26px;padding-bottom:14px;border-bottom:1px solid #e5e5e5}
        #news .news-cat.first{margin-top:0}
        #news .news-cat-title{font-size:24px;font-weight:800;line-height:1.3;color:#000;letter-spacing:.5px;padding-left:14px;border-left:5px solid #FFFF00}
        #news .news-cat-en{font-size:11px;font-weight:700;letter-spacing:3px;text-transform:uppercase;color:#888}
        #news .news-cat-more{margin-left:auto;font-size:13.5px;font-weight:800;color:#000;border-bottom:3px solid #FFFF00;padding-bottom:1px}
        #news .news-cat-more:hover{background:#FFFF00}
        @media (max-width:768px){#news .news-cat{margin:48px 0 18px}#news .news-cat-title{font-size:20px}}
      </style>'''


class NewsOrderError(Exception):
    pass


def slug_of(href):
    return re.sub(r'(-en)?\.html$', '', href)


def region(t):
    """新聞卡片區段的 (起, 迄)。第一次跑時還沒有標記，就從新聞區的 press-grid 取到區段結尾。"""
    if START in t:
        s = t.rindex('\n', 0, t.index(START)) + 1
        return s, t.index(END, s) + len(END)
    news = t.find('<section id="news"')
    if news < 0:
        raise NewsOrderError('找不到 <section id="news">')
    s = t.rindex('\n', 0, t.index('<div class="press-grid">', news)) + 1
    e = t.find('\n    </div>\n  </section>', s)
    if e < 0:
        raise NewsOrderError('新聞區結尾不是預期的 </div></section>，不敢動')
    return s, e


def render(t, lang, drop=()):
    s, e = region(t)
    body = t[s:e]
    cards = [(m.group(1), m.group(0)) for m in CARD.finditer(body)]
    # 任何寫法的卡片連結（屬性順序不同、多了別的 class）都要先數到，解析不了就停，不然重排會把它弄丟
    marks = len(re.findall(r'<a\b[^>]*class="press-card(?:\s[^"]*)?"', body))
    if marks != len(cards):
        raise NewsOrderError(f'新聞區有 {marks} 個卡片連結，只解析出 {len(cards)} 張完整卡片，結構不對，不敢動')
    cat_of = {sl: c['id'] for c in CFG['categories'] for sl in c['slugs']}
    groups = {c['id']: [] for c in CFG['categories']}
    errors, seen, dropped = [], set(), []
    for i, (href, block) in enumerate(cards):
        sl = slug_of(href)
        if sl in drop:
            if sl not in CFG['off_homepage']:
                errors.append(f'{href}：--drop 只能拿掉 off_homepage 登記過的文章，先登記原因')
            dropped.append(href)
            continue
        if href in seen:
            errors.append(f'{href}：同一張卡出現兩次')
        seen.add(href)
        if sl in CFG['off_homepage']:
            errors.append(f'{href}：已裁示不上首頁（{CFG["off_homepage"][sl]}）')
            continue
        if sl not in cat_of:
            errors.append(f'{href}：沒有登記分類 → 先加進 _build/news_categories.json')
            continue
        if sl not in CFG['dates']:
            errors.append(f'{href}：沒有登記新聞日期 → 先在 _build/news_categories.json 的 dates 加上日期與依據')
            continue
        if not DATE.search(block):
            errors.append(f'{href}：卡片上找不到日期欄 <span class="press-date">…</span>')
            continue
        ymd = CFG['dates'][sl][0]
        block = DATE.sub(f'<span class="press-date">{ymd.replace("-", ".")}</span>', block, count=1)
        groups[cat_of[sl]].append((ymd.replace('-', ''), i, href, block))
    if errors:
        raise NewsOrderError('\n   '.join(errors))

    out = [f'      {START} (generated by _build/news_order.py · 依分類分區、同一類依新聞日期新到舊 · '
           '分類與日期登記在 _build/news_categories.json · 重跑只替換本區塊) -->', STYLE]
    first = True
    for c in CFG['categories']:
        g = sorted(groups[c['id']], key=lambda x: (-int(x[0]), x[1]))
        if not g:
            continue
        title = c['zh'] if lang == 'zh' else c['en']
        sub = f'<span class="news-cat-en">{c["en"]}</span>' if lang == 'zh' else ''
        if c.get('more'):  # 分類的「看更多」連結（例：客戶案例 → 全球成功案例庫）
            m = c['more'][lang]
            sub += f'<a class="news-cat-more" href="{m["href"]}">{m["text"]}</a>'
        out.append(f'      <div class="news-cat{" first" if first else ""}" id="cat-{c["id"]}">'
                   f'<h2 class="news-cat-title">{title}</h2>{sub}</div>')
        first = False
        out.append('      <div class="press-grid">')
        for k, (_, _, href, block) in enumerate(g):
            cls = 'press-card wide' if len(g) % 2 == 1 and k == 0 else 'press-card'
            block = OPEN.sub(lambda m: f'<a href="{m.group(1)}" class="{cls}">', block, count=1)
            out.append(f'        <!-- CARD:{slug_of(href)} -->')
            out.append('        ' + block)
        out.append('      </div>')
    out.append('      ' + END)
    new = t[:s] + '\n'.join(out) + t[e:]

    # 保證：卡片一張都沒少、也沒多（--drop 指定的除外）
    before = sorted(h for h, _ in cards if h not in dropped)
    ns, ne = region(new)
    after = sorted(m.group(1) for m in CARD.finditer(new[ns:ne]))
    if before != after:
        raise NewsOrderError(f'重排前後卡片不一致：少 {sorted(set(before) - set(after))}，多 {sorted(set(after) - set(before))}')
    report = [(c[lang], [h for _, _, h, _ in sorted(groups[c['id']], key=lambda x: (-int(x[0]), x[1]))])
              for c in CFG['categories'] if groups[c['id']]]
    return new, report, dropped


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true', help='只檢查不寫檔，順序不對 exit 1')
    ap.add_argument('--drop', default='', help='要從首頁拿掉的 slug，逗號分隔（限 off_homepage 登記過的）')
    ap.add_argument('--root', default=str(ROOT))
    a = ap.parse_args()
    drop = {x for x in a.drop.split(',') if x}
    bad = 0
    for name, lang in PAGES.items():
        p = Path(a.root) / name
        t = p.read_text(encoding='utf-8')
        try:
            new, report, dropped = render(t, lang, drop)
        except NewsOrderError as ex:
            print(f'❌ {name}：\n   {ex}')
            bad = 1
            continue
        n = sum(len(h) for _, h in report)
        if new == t:
            print(f'✅ {name}：{n} 張卡，已依分類＋新聞日期排好')
            continue
        if a.check:
            print(f'❌ {name}：卡片順序或分類區塊不符規則 → 跑 python3 _build/news_order.py 重排後再推')
            bad = 1
            continue
        p.write_text(new, encoding='utf-8')
        print(f'✍️  {name}：重排 {n} 張卡' + (f'；拿掉 {", ".join(dropped)}' if dropped else ''))
        for title, hrefs in report:
            print(f'   ■ {title}（{len(hrefs)}）')
            for h in hrefs:
                print(f'      {h}')
    return bad


if __name__ == '__main__':
    sys.exit(main())
